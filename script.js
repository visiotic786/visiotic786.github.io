// ===== Typing Effect =====
const typedText = document.getElementById('typedText');
const roles = [
    'Graphic Designer',
    'VFX Artist',
    'Motion Graphics Designer',
    'Brand Designer',
    'Web Designer'
];

let roleIndex = 0;
let charIndex = 0;
let isDeleting = false;
let typeSpeed = 100;

function typeEffect() {
    const currentRole = roles[roleIndex];

    if (isDeleting) {
        typedText.textContent = currentRole.substring(0, charIndex - 1);
        charIndex--;
        typeSpeed = 50;
    } else {
        typedText.textContent = currentRole.substring(0, charIndex + 1);
        charIndex++;
        typeSpeed = 100;
    }

    if (!isDeleting && charIndex === currentRole.length) {
        typeSpeed = 2000;
        isDeleting = true;
    } else if (isDeleting && charIndex === 0) {
        isDeleting = false;
        roleIndex = (roleIndex + 1) % roles.length;
        typeSpeed = 500;
    }

    setTimeout(typeEffect, typeSpeed);
}

// Start typing after page load
setTimeout(typeEffect, 1000);

// ===== Counter Animation =====
const counters = document.querySelectorAll('.stat-number');
const observerOptions = {
    threshold: 0.5
};

const counterObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const counter = entry.target;
            const target = parseInt(counter.getAttribute('data-count'));
            const duration = 2000;
            const step = target / (duration / 16);
            let current = 0;

            const updateCounter = () => {
                current += step;
                if (current < target) {
                    counter.textContent = Math.floor(current) + '+';
                    requestAnimationFrame(updateCounter);
                } else {
                    counter.textContent = target + '+';
                }
            };

            updateCounter();
            counterObserver.unobserve(counter);
        }
    });
}, observerOptions);

counters.forEach(counter => counterObserver.observe(counter));

// ===== Skill Bar Animation =====
const skillCards = document.querySelectorAll('.skill-card');

const skillObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            const card = entry.target;
            const percent = card.getAttribute('data-percent');
            const progressBar = card.querySelector('.skill-progress');
            progressBar.style.width = percent + '%';
            skillObserver.unobserve(card);
        }
    });
}, { threshold: 0.5 });

skillCards.forEach(card => skillObserver.observe(card));

// ===== Scroll Reveal Animation =====
const revealElements = document.querySelectorAll(
    '.section-header, .about-image, .about-content, .skill-card, .timeline-item, .portfolio-item, .education-card, .extras-card, .contact-info, .contact-form'
);

revealElements.forEach(el => {
    el.classList.add('reveal');
    if (el.classList.contains('about-image') || el.classList.contains('contact-info')) {
        el.classList.add('reveal-left');
    } else if (el.classList.contains('about-content') || el.classList.contains('contact-form')) {
        el.classList.add('reveal-right');
    }
});

const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry, index) => {
        if (entry.isIntersecting) {
            setTimeout(() => {
                entry.target.classList.add('active');
            }, index * 80);
            revealObserver.unobserve(entry.target);
        }
    });
}, { threshold: 0.1 });

revealElements.forEach(el => revealObserver.observe(el));

